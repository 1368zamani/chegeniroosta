    private function seedTitles(array $rows, string $type, bool $optional): void
    {
        foreach ($rows as $i => $row) {
            [$code, $nameFa, $formulaKey, $note] = array_pad($row, 4, null);

            TariffTitle::updateOrCreate(
                ['code' => $code],
                [
                    'type'           => $type,
                    'name_fa'        => $nameFa,
                    'formula_key'    => $formulaKey,
                    'statutory_note' => $note,
                    'is_optional'    => $optional,
                    'sort_order'     => $i + 1,
                    'is_active'      => true,
                ]
            );
        }
